/** 주제 설명. 사전에 새 주제가 생겼는데 설명이 아직 없으면 이름만 쓴 한 문장으로 버틴다(테스트가 빠진 주제를 잡는다) */
export function topicBlurb(id: string, name: string): string {
  return TOPIC_BLURBS[id] ?? `${name} 분야의 새 소식을 다뤄요.`;
}

/** 설명의 첫 문장(메타 description용). 문장은 마침표 뒤 공백으로 나눈다('Next.js'처럼 공백 없는 점은 문장 끝이 아니다) */
export function firstSentence(text: string): string {
  return text.split(/(?<=[.!?])\s+/)[0] ?? text;
}

/**
 * 메타 description: 주제 설명 첫 문장 + 검색어 한 줄(2026-11-10 용어 정책: 검색어 '뉴스 요약'은 제목·설명·키워드에만, 화면은 '소식').
 * 160자 안팎으로 맞춘다. 쪽을 넘긴 주소(?page=2)는 쪽 번호를 붙여 쪽마다 설명이 다르게 한다
 */
export function topicMetaDescription(id: string, name: string, page = 1): string {
  const head = `${firstSentence(topicBlurb(id, name))} ${name} 뉴스 요약을 원문 링크와 함께 최신순으로 모았어요.`;
  return page > 1 ? `${head} (${page}쪽)` : head;
}
